TEST(GzipTest, RejectsTruncatedStream)
{
	// 트레일러까지 잘라낸다 — inflate 자체가 입력 부족으로 끝나는지, 아니면 트레일러 부재로 걸리는지
	// 어느 쪽이든 "잘렸다" 로 보고해야 한다.
	const std::vector<byte_t> truncated(reinterpret_cast<const byte_t*>(std::begin(RepeatGz)), reinterpret_cast<const byte_t*>(std::begin(RepeatGz)) + 60);

	const auto result = GzipDecompress(truncated);
	ASSERT_TRUE(result.IsError());
	EXPECT_EQ(result.Error().Kind(), CompressErrorKind::TRUNCATED_STREAM);
}

TEST(GzipTest, DetectsCorruptedPayloadByChecksum)
{
	// 트레일러의 CRC32 를 뒤집는다 — 본문은 정상 해제되지만 체크섬이 어긋나야 한다.
	std::vector<byte_t> corrupted(std::begin(RepeatGz), std::end(RepeatGz));
	corrupted[corrupted.size() - 8] ^= byte_t{ 0xFF };

	const auto result = GzipDecompress(corrupted);
	ASSERT_TRUE(result.IsError());
	EXPECT_EQ(result.Error().Kind(), CompressErrorKind::CHECKSUM_MISMATCH);
}

