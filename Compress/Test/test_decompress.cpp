TEST(ZlibTest, DecompressesZlibContainer)
{
	// zlib 컨테이너는 gzip 과 같은 raw DEFLATE 본문을 다른 껍데기로 감싼 것이다. gzip 벡터의 본문을
	// 떼어내 zlib 헤더/트레일러로 다시 감싸면, 외부 도구가 만든 DEFLATE 를 zlib 경로로 검증할 수 있다.
	const auto gz = AsSpan(RepeatGz);
	const auto deflateBody = gz.subspan(10, gz.size() - 10 - 8);

	std::string expected;
	for (int_t i = 0; i < 200; ++i) expected += "The quick brown fox jumps over the lazy dog. ";

	std::vector<byte_t> zlibStream;
	zlibStream.push_back(byte_t{ 0x78 }); // CMF: deflate, 32KB 윈도우
	zlibStream.push_back(byte_t{ 0x9C }); // FLG: 체크비트 맞음, FDICT 없음
	zlibStream.insert(zlibStream.end(), deflateBody.begin(), deflateBody.end());

	const uint_t adler = internal::Adler32({ reinterpret_cast<const byte_t*>(expected.data()), expected.size() });
	for (int_t shift = 24; shift >= 0; shift -= 8) zlibStream.push_back(static_cast<byte_t>((adler >> shift) & 0xFF)); // 빅엔디언

	const auto result = ZlibDecompress(zlibStream);
	ASSERT_TRUE(result.IsOk()) << result.Error().What();
	EXPECT_EQ(AsString(result.Value()), expected);
}

TEST(ZlibTest, RejectsBadHeaderCheckBits)
{
	// 최소 길이(헤더 2 + Adler 4) 는 채운다 — 그러지 않으면 길이 검사가 먼저 걸려 검사비트 경로를 지나치지 못한다.
		const std::vector<byte_t> stream{ byte_t{ 0x78 }, byte_t{ 0x9D }, byte_t{ 0x00 }, byte_t{ 0x00 }, byte_t{ 0x00 }, byte_t{ 0x00 } }; // (0x78<<8|0x9D) % 31 != 0

	const auto result = ZlibDecompress(stream);
	ASSERT_TRUE(result.IsError());
	EXPECT_EQ(result.Error().Kind(), CompressErrorKind::MALFORMED_STREAM);
}

TEST(ZlibTest, RejectsPresetDictionary)
{
	// FDICT(0x20) 은 양쪽이 같은 사전을 미리 공유해야 해서 HTTP 에서는 쓰이지 않는다 — 추측 대신 거부.
	const std::vector<byte_t> stream{ byte_t{ 0x78 }, byte_t{ 0xBB }, byte_t{ 0x00 }, byte_t{ 0x00 }, byte_t{ 0x00 }, byte_t{ 0x00 } }; // (0x78<<8|0xBB) % 31 == 0, FDICT 켜짐

	const auto result = ZlibDecompress(stream);
	ASSERT_TRUE(result.IsError());
	EXPECT_EQ(result.Error().Kind(), CompressErrorKind::UNSUPPORTED_ENCODING);
}



TEST(ChecksumTest, MatchesPublishedVectors)
{
	// 널리 인용되는 값들이라 우리 구현이 아니라 규격을 검증한다.
	const std::string_view check = "123456789";
	const std::span<const byte_t> bytes{ reinterpret_cast<const byte_t*>(check.data()), check.size() };

	EXPECT_EQ(internal::Crc32(bytes), 0xCBF43926u);   // CRC-32/ISO-HDLC 표준 체크값
	EXPECT_EQ(internal::Adler32(bytes), 0x091E01DEu); // Adler-32 of "123456789"
}

