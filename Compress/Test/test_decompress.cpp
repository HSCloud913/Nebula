	/** @brief C 배열을 해제기 입력 span 으로 바꿉니다. */
	template<std::size_t N>
	[[nodiscard]] std::span<const byte_t> AsSpan(const unsigned char (&_bytes)[N]) noexcept
	{
		return { reinterpret_cast<const byte_t*>(_bytes), N };
	}

